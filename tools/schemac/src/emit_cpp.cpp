std::string emit_cpp_header(const Model& model, const SchemaFile& file) {
  (void)model;
  std::ostringstream out;
  out << "// Generated by schemac from " << file.stem << ".schema. Do not edit; edit the schema.\n";
  out << "#pragma once\n\n";
  out << "#include <core/base/types.h>\n";
  out << "#include <core/containers/flat_map.h>\n";
  out << "#include <core/containers/vector.h>\n";
  out << "#include <core/ids/id128.h>\n";
  out << "#include <core/json/json_value.h>\n";
  out << "#include <core/math/math.h>\n";
  out << "#include <core/schema/type_info.h>\n\n";
  out << "#include <array>\n#include <optional>\n#include <string>\n";
  for (const std::string& imp : file.imports)
    out << "#include <schemas/" << imp << ".h>\n";
  out << "\n";

  const std::string ns = ns_to_cpp(file.ns);
  out << "namespace " << ns << " {\n\n";

  for (const EnumDecl& e : file.enums) {
    emit_comment(out, "", e.doc);
    out << "enum class " << e.name << " : engine::" << e.underlying << " {\n";
    for (const EnumValue& v : e.values) {
      emit_comment(out, "  ", v.doc);
      out << "  " << v.name << " = " << v.value << ",\n";
    }
    out << "};\n\n";
  }

  for (const StructDecl& s : file.structs) {
    emit_comment(out, "", s.doc);
    out << "struct " << s.name << " {\n";
    out << "  static constexpr engine::u16 k_schema_version = " << s.version << ";\n\n";
    for (const Field& f : s.fields) {
      emit_comment(out, "  ", f.doc);
      out << "  " << cpp_type(f.type) << " " << f.name;
      const std::string init = default_initializer(f);
      if (init == "{}") {
        out << "{};\n";
      } else {
        out << " = " << init << ";\n";
      }
    }
    out << "\n  bool operator==(const " << s.name << "&) const = default;\n";
    out << "};\n\n";
  }

  out << "namespace schema_detail {\n";
  for (const EnumDecl& e : file.enums)
    out << "extern const engine::schema::TypeInfo " << e.name << "_info;\n";
  for (const StructDecl& s : file.structs)
    out << "extern const engine::schema::TypeInfo " << s.name << "_info;\n";
  out << "}  // namespace schema_detail\n\n";
  out << "}  // namespace " << ns << "\n\n";

  out << "namespace engine::schema {\n";
  for (const EnumDecl& e : file.enums) {
    out << "template <>\ninline const TypeInfo& type_of<" << ns << "::" << e.name << ">() { return "
        << ns << "::schema_detail::" << e.name << "_info; }\n";
  }
  for (const StructDecl& s : file.structs) {
    out << "template <>\ninline const TypeInfo& type_of<" << ns << "::" << s.name << ">() { return "
        << ns << "::schema_detail::" << s.name << "_info; }\n";
  }
  out << "}  // namespace engine::schema\n";
  return out.str();
}

std::string emit_cpp_source(const Model& model, const SchemaFile& file) {
  (void)model;
  std::ostringstream out;
  out << "// Generated by schemac from " << file.stem << ".schema. Do not edit; edit the schema.\n";
  out << "#include <schemas/" << file.stem << ".h>\n\n";
  out << "#include <core/schema/ops.h>\n\n";
  out << "#include <cstddef>\n#include <span>\n\n";
  out << "#if defined(__clang__) || defined(__GNUC__)\n";
  out << "#pragma GCC diagnostic ignored \"-Winvalid-offsetof\"\n";
  out << "#endif\n\n";

  const std::string ns = ns_to_cpp(file.ns);
  out << "namespace " << ns << "::schema_detail {\n\n";
  out << "namespace {\n\n";

  for (const EnumDecl& e : file.enums) {
    out << "constexpr engine::schema::EnumValueInfo " << e.name << "_values[] = {\n";
    for (const EnumValue& v : e.values) {
      out << "    {\"" << v.name << "\", " << v.value << ", \"" << escape_cpp_string(v.doc)
          << "\"},\n";
    }
    out << "};\n\n";
  }

  for (const StructDecl& s : file.structs) {
    int counter = 0;
    std::vector<std::string> refs;
    for (const Field& f : s.fields)
      refs.push_back(emit_type_ref(out, f.type, s.name + "_" + f.name, counter));
    out << "\n";
    if (s.fields.empty()) {
      out << "constexpr std::span<const engine::schema::FieldInfo> " << s.name << "_fields{};\n\n";
    } else {
      out << "constexpr engine::schema::FieldInfo " << s.name << "_fields[] = {\n";
      for (size_t i = 0; i < s.fields.size(); ++i) {
        const Field& f = s.fields[i];
        std::string flags = "0";
        if (f.transient) flags += " | engine::schema::FieldFlag::transient";
        if (f.deprecated) flags += " | engine::schema::FieldFlag::deprecated";
        out << "    {\"" << f.name << "\", " << refs[i] << ", static_cast<engine::u32>(offsetof("
            << s.name << ", " << f.name << ")), " << f.since << ", static_cast<engine::u16>("
            << flags << "), \"" << escape_cpp_string(f.doc) << "\"},\n";
      }
      out << "};\n\n";
    }
  }
  out << "}  // namespace\n\n";

  for (const EnumDecl& e : file.enums) {
    out << "extern const engine::schema::TypeInfo " << e.name << "_info{\n";
    out << "    .qualified_name = \"" << file.ns << "." << e.name << "\",\n";
    out << "    .name = \"" << e.name << "\",\n";
    out << "    .ns = \"" << file.ns << "\",\n";
    out << "    .kind = engine::schema::Kind::Enum,\n";
    out << "    .size = sizeof(" << e.name << "),\n";
    out << "    .align = alignof(" << e.name << "),\n";
    out << "    .version = 1,\n";
    out << "    .tag = \"" << escape_cpp_string(e.tag) << "\",\n";
    out << "    .doc = \"" << escape_cpp_string(e.doc) << "\",\n";
    out << "    .fields = {},\n";
    out << "    .values = std::span<const engine::schema::EnumValueInfo>(" << e.name
        << "_values),\n";
    out << "    .enum_underlying = engine::schema::Kind::"
        << kind_enum_for_primitive_name(e.underlying) << ",\n";
    out << "    .ops = nullptr,\n";
    out << "};\n\n";
  }
  for (const StructDecl& s : file.structs) {
    out << "extern const engine::schema::TypeInfo " << s.name << "_info{\n";
    out << "    .qualified_name = \"" << file.ns << "." << s.name << "\",\n";
    out << "    .name = \"" << s.name << "\",\n";
    out << "    .ns = \"" << file.ns << "\",\n";
    out << "    .kind = engine::schema::Kind::Struct,\n";
    out << "    .size = sizeof(" << s.name << "),\n";
    out << "    .align = alignof(" << s.name << "),\n";
    out << "    .version = " << s.version << ",\n";
    out << "    .tag = \"" << escape_cpp_string(s.tag) << "\",\n";
    out << "    .doc = \"" << escape_cpp_string(s.doc) << "\",\n";
    if (s.fields.empty()) {
      out << "    .fields = " << s.name << "_fields,\n";
    } else {
      out << "    .fields = std::span<const engine::schema::FieldInfo>(" << s.name << "_fields),\n";
    }
    out << "    .values = {},\n";
    out << "    .enum_underlying = engine::schema::Kind::U32,\n";
    out << "    .ops = &engine::schema::StructOpsFor<" << s.name << ">::ops,\n";
    out << "};\n\n";
  }

  out << "namespace {\n";
  out << "const engine::schema::TypeInfo* const k_all_types[] = {\n";
  for (const EnumDecl& e : file.enums)
    out << "    &" << e.name << "_info,\n";
  for (const StructDecl& s : file.structs)
    out << "    &" << s.name << "_info,\n";
  out << "};\n";
  out << "const engine::schema::Registrar k_registrar(k_all_types, sizeof(k_all_types) / "
         "sizeof(k_all_types[0]));\n";
  out << "}  // namespace\n\n";
  out << "}  // namespace " << ns << "::schema_detail\n";
  return out.str();
}

