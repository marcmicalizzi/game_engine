std::string kind_enum(const TypeExpr& t) {
  switch (t.kind) {
    case TypeExpr::Kind::Primitive: {
      if (t.name == "bool") return "Bool";
      if (t.name == "string") return "String";
      if (t.name == "bytes") return "Bytes";
      if (t.name == "id128") return "Id128";
      std::string k = t.name;
      k[0] = static_cast<char>(std::toupper(static_cast<unsigned char>(k[0])));
      return k;  // u8 -> U8, f32 -> F32
    }
    case TypeExpr::Kind::Named: return t.resolved_is_enum ? "Enum" : "Struct";
    case TypeExpr::Kind::Optional: return "Optional";
    case TypeExpr::Kind::Array: return "Array";
    case TypeExpr::Kind::FixedArray: return "FixedArray";
    case TypeExpr::Kind::Map: return "Map";
  }
  return "Bool";
}

std::string kind_enum_for_primitive_name(const std::string& name) {
  TypeExpr t;
  t.kind = TypeExpr::Kind::Primitive;
  t.name = name;
  return kind_enum(t);
}

std::string info_symbol(const TypeExpr& t) {
  // a::b::schema_detail::Name_info
  const size_t sep = t.resolved_cpp.rfind("::");
  const std::string ns = sep == std::string::npos ? "" : t.resolved_cpp.substr(0, sep);
  const std::string name =
      sep == std::string::npos ? t.resolved_cpp : t.resolved_cpp.substr(sep + 2);
  return (ns.empty() ? "" : ns + "::") + "schema_detail::" + name + "_info";
}

// Emits a doc string as one or more `// ` comment lines at the given indent.
void emit_comment(std::ostringstream& out, const std::string& indent, const std::string& doc) {
  if (doc.empty()) return;
  size_t start = 0;
  while (start <= doc.size()) {
    const size_t nl = doc.find('\n', start);
    const std::string line =
        doc.substr(start, nl == std::string::npos ? std::string::npos : nl - start);
    out << indent << "// " << line << "\n";
    if (nl == std::string::npos) break;
    start = nl + 1;
  }
}

std::string default_initializer(const Field& f) {
  const TypeExpr& t = f.type;
  switch (f.default_kind) {
    case DefaultKind::None:
    case DefaultKind::Null:
    case DefaultKind::EmptyArray: return "{}";
    case DefaultKind::Bool: return f.default_text;
    case DefaultKind::Int:
      if (t.name == "f32") return f.default_text + ".0f";
      if (t.name == "f64") return f.default_text + ".0";
      if (t.name == "u64") return f.default_text + "ull";
      if (t.name == "i64") return f.default_text + "ll";
      return f.default_text;
    case DefaultKind::Float: return t.name == "f32" ? f.default_text + "f" : f.default_text;
    case DefaultKind::String: return "\"" + escape_cpp_string(f.default_text) + "\"";
    case DefaultKind::Ident: return t.resolved_cpp + "::" + f.default_text;
  }
  return "{}";
}

// Emits constexpr TypeRef constants for `t` and its element types; returns the outermost name.
std::string emit_type_ref(std::ostringstream& out, const TypeExpr& t, const std::string& prefix,
                          int& counter) {
  std::string element_ref, key_ref;
  if (t.element) element_ref = emit_type_ref(out, *t.element, prefix, counter);
  if (t.key) key_ref = emit_type_ref(out, *t.key, prefix, counter);
  const std::string name = prefix + "_r" + std::to_string(counter++);
  const std::string cpp = cpp_type(t);
  out << "constexpr engine::schema::TypeRef " << name << "{\n";
  out << "    .kind = engine::schema::Kind::" << kind_enum(t) << ",\n";
  out << "    .fixed_count = "
      << (t.kind == TypeExpr::Kind::FixedArray ? std::to_string(t.count) : "0") << ",\n";
  out << "    .size = sizeof(" << cpp << "),\n";
  out << "    .align = alignof(" << cpp << "),\n";
  out << "    .type = " << (t.kind == TypeExpr::Kind::Named ? "&" + info_symbol(t) : "nullptr")
      << ",\n";
  out << "    .element = " << (element_ref.empty() ? "nullptr" : "&" + element_ref) << ",\n";
  out << "    .key = " << (key_ref.empty() ? "nullptr" : "&" + key_ref) << ",\n";
  out << "    .optional_ops = "
      << (t.kind == TypeExpr::Kind::Optional ? "&engine::schema::OptionalOpsFor<" + cpp + ">::ops"
                                             : "nullptr")
      << ",\n";
  std::string array_ops = "nullptr";
  if (t.kind == TypeExpr::Kind::Array ||
      (t.kind == TypeExpr::Kind::Primitive && t.name == "bytes")) {
    array_ops = "&engine::schema::ArrayOpsFor<" + cpp + ">::ops";
  } else if (t.kind == TypeExpr::Kind::FixedArray) {
    array_ops = "&engine::schema::FixedArrayOpsFor<" + cpp + ">::ops";
  }
  out << "    .array_ops = " << array_ops << ",\n";
  out << "    .map_ops = "
      << (t.kind == TypeExpr::Kind::Map ? "&engine::schema::MapOpsFor<" + cpp + ">::ops"
                                        : "nullptr")
      << ",\n";
  out << "};\n";
  return name;
}

